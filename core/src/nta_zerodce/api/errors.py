"""JSON error model for the HTTP API.

Every non-2xx response, including those generated by the framework (unknown path, wrong
method, validation failures) and unexpected failures, has the body
``{"error": {"code": str, "message": str}}`` (contract: docs/ARCHITECTURE.md, "HTTP contract").
Messages are fixed, human-readable strings; they never contain uploaded file names, server
paths or exception text.
"""

from __future__ import annotations

from typing import Any

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException

# Codes defined by the HTTP contract.
INVALID_IMAGE = "invalid_image"
TOO_LARGE = "too_large"
UNSUPPORTED_TYPE = "unsupported_type"
BAD_OPTION = "bad_option"
MODEL_NOT_LOADED = "model_not_loaded"
SERVER_BUSY = "server_busy"
# Codes for framework-level and unexpected failures (not part of the web client's contract).
NOT_FOUND = "not_found"
METHOD_NOT_ALLOWED = "method_not_allowed"
HTTP_ERROR = "http_error"
INTERNAL_ERROR = "internal_error"

_MAX_ECHOED_PATH = 200


class ApiError(Exception):
    """An error that is reported to the client as JSON with a fixed status and code."""

    def __init__(
        self,
        status_code: int,
        code: str,
        message: str,
        headers: dict[str, str] | None = None,
    ) -> None:
        super().__init__(message)
        self.status_code = status_code
        self.code = code
        self.message = message
        self.headers = headers


def error_body(code: str, message: str) -> dict[str, Any]:
    """Return the contract error body for ``code`` and ``message``."""
    return {"error": {"code": code, "message": message}}


def error_response(
    status_code: int, code: str, message: str, headers: dict[str, str] | None = None
) -> JSONResponse:
    """Build the JSON error response for a status, code and message."""
    return JSONResponse(error_body(code, message), status_code=status_code, headers=headers)


def _printable(text: str) -> str:
    """Return ``text`` truncated and with non-printable characters replaced by ``?``."""
    cleaned = "".join(ch if ch.isprintable() else "?" for ch in text)
    return cleaned[:_MAX_ECHOED_PATH]


async def _api_error_handler(_: Request, exc: Exception) -> JSONResponse:
    assert isinstance(exc, ApiError)
    return error_response(exc.status_code, exc.code, exc.message, exc.headers)


async def _http_error_handler(request: Request, exc: Exception) -> JSONResponse:
    assert isinstance(exc, StarletteHTTPException)
    headers = dict(exc.headers) if exc.headers else None
    if exc.status_code == 404:
        message = f"No route for {_printable(request.url.path)}."
        return error_response(404, NOT_FOUND, message, headers)
    if exc.status_code == 405:
        return error_response(405, METHOD_NOT_ALLOWED, "Method not allowed for this path.", headers)
    return error_response(exc.status_code, HTTP_ERROR, "The request could not be handled.", headers)


async def _validation_error_handler(_: Request, exc: Exception) -> JSONResponse:
    assert isinstance(exc, RequestValidationError)
    return error_response(422, BAD_OPTION, "The request parameters are invalid.")


def install_exception_handlers(app: FastAPI) -> None:
    """Register JSON handlers for API, HTTP (404/405/...) and validation errors on ``app``."""
    app.add_exception_handler(ApiError, _api_error_handler)
    app.add_exception_handler(StarletteHTTPException, _http_error_handler)
    app.add_exception_handler(RequestValidationError, _validation_error_handler)
